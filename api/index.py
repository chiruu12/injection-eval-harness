"""A read-only view of the committed results, so the repo has a deployable entrypoint.

This exists because the repository is wired to a Vercel project, and Vercel needs
a Python entrypoint to build anything at all. Nothing in the evaluation depends on
it: the harness is a CLI, `make table` regenerates the numbers, and this module is
never imported by src/injection_eval.

Two constraints shape it. It is stdlib only, because the project's real
dependencies include torch and transformers and a serverless function has no
business pulling several hundred megabytes to serve a JSON file. And it serves the
committed results verbatim rather than computing anything, because a number that
appears here and nowhere else would be a second source of truth for a table whose
whole point is that it has one.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable
from http import HTTPStatus
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "results.json"
MANIFEST = ROOT / "results" / "manifest.json"
TABLES = ROOT / "results" / "TABLES.md"

_JSON = "application/json; charset=utf-8"
_TEXT = "text/plain; charset=utf-8"

# The committed table is regenerated by a workflow, not by this function, so a
# response may be served for as long as the deployment lives.
_CACHE = "public, max-age=0, s-maxage=3600"

_ROUTES: dict[str, tuple[Path, str]] = {
    "/results.json": (RESULTS, _JSON),
    "/manifest.json": (MANIFEST, _JSON),
    "/tables.md": (TABLES, _TEXT),
}

_INDEX = """injection-eval-harness

Contamination-controlled evaluation of prompt-injection detectors.
Source and findings: https://github.com/chiruu12/injection-eval-harness

  /results.json   every reported number, as regenerated by `make table`
  /manifest.json  pinned model and dataset shas, split checksums, seed
  /tables.md      the rendered tables

These are the committed artifacts, served verbatim. To regenerate them rather
than trust them, see the reproduce workflow or `make verify`.
"""


def _body(path: str) -> tuple[int, str, bytes]:
    """Status, content type and bytes for one path. Never raises on a missing file."""
    if path in ("", "/", "/index.html"):
        return HTTPStatus.OK, _TEXT, _INDEX.encode("utf-8")
    route = _ROUTES.get(path)
    if route is None:
        known = " ".join(sorted(_ROUTES))
        return HTTPStatus.NOT_FOUND, _TEXT, f"not found. try: / {known}\n".encode()
    target, content_type = route
    if not target.is_file():
        # The deployment was built without results/, which is a packaging fault
        # rather than a request fault, and saying so beats an empty 200.
        message = f"{target.name} is not in this deployment\n"
        return HTTPStatus.INTERNAL_SERVER_ERROR, _TEXT, message.encode("utf-8")
    return HTTPStatus.OK, content_type, target.read_bytes()


def app(environ: dict[str, Any], start_response: Callable[..., Any]) -> Iterable[bytes]:
    """WSGI entrypoint. Vercel's Python runtime calls this."""
    method = environ.get("REQUEST_METHOD", "GET").upper()
    path = environ.get("PATH_INFO", "/")
    if method not in ("GET", "HEAD"):
        start_response("405 Method Not Allowed", [("Allow", "GET, HEAD")])
        return [b""]
    status, content_type, payload = _body(path)
    headers = [
        ("Content-Type", content_type),
        ("Content-Length", str(len(payload))),
        ("Cache-Control", _CACHE),
    ]
    start_response(f"{status.value} {status.phrase}", headers)
    return [b""] if method == "HEAD" else [payload]
